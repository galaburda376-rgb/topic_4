def fill(template: str, **pools) -> str:
    """Подставляет случайные значения из словарей в шаблон по именам слотов."""
    text = template
    for slot, pool in pools.items():
        token = "{" + slot + "}"
        while token in text:
            text = text.replace(token, random.choice(pool), 1)
    # отдельно обрабатываем служебный слот {cta.lower}, который встречается в одном шаблоне
    while "{cta.lower}" in text:
        text = text.replace("{cta.lower}", random.choice(ctas).lower(), 1)
    return text


def add_noise(text: str) -> str:
    """Имитирует 'грязные' сообщения: опечатки, слипшиеся слова, лишние символы."""
    noise_type = random.choice(["dup_letter", "merge_words", "extra_punct", "drop_letter"])
    if noise_type == "dup_letter" and len(text) > 3:
        i = random.randint(1, len(text) - 2)
        text = text[:i] + text[i] + text[i:]
    elif noise_type == "merge_words":
        words = text.split(" ")
        if len(words) > 3:
            i = random.randint(0, len(words) - 2)
            words[i] = words[i] + words[i + 1]
            del words[i + 1]
            text = " ".join(words)
    elif noise_type == "extra_punct":
        text = re.sub(r"([!?.])", lambda m: m.group(1) * random.randint(1, 3), text, count=1)
    elif noise_type == "drop_letter" and len(text) > 5:
        i = random.randint(1, len(text) - 2)
        text = text[:i] + text[i + 1:]
    return text


def generate_class(label: str, templates, pools, n: int, hard_templates=None, hard_rate=0.0):
    seen = set()
    rows = []
    attempts = 0
    while len(rows) < n and attempts < n * 20:
        attempts += 1
        if hard_templates and random.random() < hard_rate:
            template = random.choice(hard_templates)
        else:
            template = random.choice(templates)
        text = fill(template, **pools)
        if text in seen:
            continue
        seen.add(text)
        is_noisy = random.random() < NOISE_RATE
        if is_noisy:
            text = add_noise(text)
        rows.append((text, label, int(is_noisy)))
    return rows


def flip_labels(rows, rate):
    """
    Случайно переставляет метку класса у части сообщений — имитация шума
    разметки, который неизбежен при автоматической/слабой разметке реальных
    Telegram-данных (например, если метки ставились эвристикой или краудсорс-
    разметчиком). Без этого шума классы разделяются идеально (accuracy=100%),
    что нереалистично: у модели не может быть права на ошибку, если в данных
    нет противоречий. Возвращает новый список (text, label, is_noisy, is_flipped).
    """
    other = {"spam": "clickbait", "clickbait": "spam"}
    out = []
    for text, label, is_noisy in rows:
        if random.random() < rate:
            out.append((text, other[label], is_noisy, 1))
        else:
            out.append((text, label, is_noisy, 0))
    return out


def main():
    spam_pools = dict(
        hook=hooks, offer=offers, amount=amounts, period=periods,
        cta=ctas, contact=contacts, percent=percents, deadline=deadlines,
        number=numbers,
    )
    clickbait_pools = dict(
        subject=subjects, topic=topics, event=events, reaction=reactions,
        number=numbers, effect=effects, action=actions,
    )

    rows = []
    rows += generate_class(
        "spam", spam_templates, spam_pools, N_PER_CLASS,
        hard_templates=hard_spam_templates, hard_rate=HARD_RATE,
    )
    rows += generate_class(
        "clickbait", clickbait_templates, clickbait_pools, N_PER_CLASS,
        hard_templates=hard_clickbait_templates, hard_rate=HARD_RATE,
    )
    random.shuffle(rows)
    rows = flip_labels(rows, LABEL_NOISE_RATE)

    out_path = "data/dataset.csv"
    with open(out_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["text", "label", "is_noisy", "is_label_flipped"])
        writer.writerows(rows)

    n_noisy = sum(r[2] for r in rows)
    n_flipped = sum(r[3] for r in rows)
    print(f"Готово: {len(rows)} сообщений сохранено в {out_path}")
    print(f"  spam: {sum(1 for r in rows if r[1] == 'spam')}")
    print(f"  clickbait: {sum(1 for r in rows if r[1] == 'clickbait')}")
    print(f"  текстового шума (опечатки): {n_noisy} ({n_noisy / len(rows):.1%})")
    print(f"  шума разметки (перепутанная метка): {n_flipped} ({n_flipped / len(rows):.1%})")


if __name__ == "__main__":
    main()
