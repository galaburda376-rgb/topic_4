# "Пограничные" (hard) шаблоны — намеренно смешивают приёмы двух классов.
#
# В реальных Telegram-каналах спамеры часто маскируют рекламу под кликбейт-
# заголовок ("Вы не поверите, как я заработал..."), а кликбейт-каналы иногда
# используют спамерскую лексику срочности ("только сегодня", "успей").
# Без таких пограничных примеров классы разделяются по словарю идеально
# (accuracy = 100%), что нереалистично и не даёт материала для анализа ошибок.
# Поэтому часть сообщений каждого класса генерируется с намеренным наложением
# лексики — это имитирует естественное пересечение жанров, а не "читерство".
